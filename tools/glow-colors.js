/* Works out the hover / hold aura colour of every perk, add-on, item, offering and killer power — and the border colour of each survivor portrait — from its own picture,
   and writes it to js/glow-colors.js  (window.DBD_GLOW = { "<id>": "#rrggbb" }).

   The colour is the dominant coloured area of the picture (the diamond / square background, not the artwork or the dark
   frame), brightened a little so it shows up as a glow — the same idea as killerGlow in js/data.js.

   Run, from the project folder, after adding or changing pictures / entries:     node tools/glow-colors.js
   (the first time: npm install --prefix tools)
   Not happy with one colour? Put it in OVERRIDES below, it wins over the sampled one. */

const sharp = require("sharp");
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");

// id → "#rrggbb", for colours that came out wrong
const OVERRIDES = {};

function loadData() {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(root, "js", "data.js"), "utf8"), sandbox);
  return sandbox.window.DBD_DATA;
}

/* everything with a picture that has an aura: [id, img path] */
function entries(D) {
  const out = [];
  const add = (e) => e && e.id && e.img && out.push([e.id, e.img]);
  [D.killerPerks, D.survivorPerks, D.offerings, D.survivorItems, D.survivorAddons, D.survivors].forEach((l) => (l || []).forEach(add));
  (D.killers || []).forEach((k) => {
    (k.addons || []).forEach(add);
    if (k.powerImg) out.push(["pw-" + k.id, k.powerImg]);
  });
  return out;
}

function rgb2hsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  if (!d) return [0, 0, l];
  const s = d / (1 - Math.abs(2 * l - 1));
  let h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [((h * 60) + 360) % 360, s, l];
}
function hsl2hex(h, s, l) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return "#" + [r, g, b].map((v) => Math.round((v + m) * 255).toString(16).padStart(2, "0")).join("");
}

async function sample(file) {
  const { data, info } = await sharp(file).resize(48, 48, { fit: "fill" }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const BUCKETS = 24; // hue buckets of 15°
  const bins = Array.from({ length: BUCKETS }, () => ({ w: 0, r: 0, g: 0, b: 0 }));
  let grey = { w: 0, l: 0 };
  for (let i = 0; i < info.width * info.height; i++) {
    const [r, g, b, a] = [data[i * 4], data[i * 4 + 1], data[i * 4 + 2], data[i * 4 + 3]];
    if (a < 200) continue;
    const [h, s, l] = rgb2hsl(r, g, b);
    if (l < 0.12 || l > 0.92) continue; // black frame / white artwork
    if (s < 0.22) { grey.w++; grey.l += l; continue; }
    const bin = bins[Math.floor(h / 15) % BUCKETS], w = s * (1 - Math.abs(2 * l - 1)); // vivid mid-tones count most
    bin.w += w; bin.r += r * w; bin.g += g * w; bin.b += b * w;
  }
  // a hue bucket plus its two neighbours, so a gradient doesn't split between buckets
  let best = -1, bestW = 0;
  for (let i = 0; i < BUCKETS; i++) {
    const w = bins[i].w + bins[(i + 1) % BUCKETS].w + bins[(i + BUCKETS - 1) % BUCKETS].w;
    if (w > bestW) { bestW = w; best = i; }
  }
  if (best < 0 || bestW < 3) { // grey / white / black pictures → neutral light grey
    const l = grey.w ? grey.l / grey.w : 0.6;
    return hsl2hex(0, 0, Math.min(0.75, Math.max(0.5, l + 0.15)));
  }
  let w = 0, r = 0, g = 0, b = 0;
  for (const i of [best, (best + 1) % BUCKETS, (best + BUCKETS - 1) % BUCKETS]) { w += bins[i].w; r += bins[i].r; g += bins[i].g; b += bins[i].b; }
  const [h, s, l] = rgb2hsl(r / w, g / w, b / w);
  return hsl2hex(h, Math.max(s, 0.6), Math.min(0.62, Math.max(0.5, l + 0.1))); // brightened, never washed out
}

(async () => {
  const list = entries(loadData());
  const out = {};
  const missing = [];
  for (const [id, img] of list) {
    const file = path.join(root, img);
    if (!fs.existsSync(file)) { missing.push(img); continue; }
    out[id] = OVERRIDES[id] || (await sample(file));
  }
  const body = Object.keys(out).sort().map((id) => `  "${id}": "${out[id]}"`).join(",\n");
  fs.writeFileSync(path.join(root, "js", "glow-colors.js"),
`/* Generated by tools/glow-colors.js — do not edit by hand (put fixes in OVERRIDES in that script).
   Aura colour per perk / add-on / item / offering / killer power, sampled from its picture. */
window.DBD_GLOW = {
${body}
};
`);
  console.log(`${Object.keys(out).length} colours written to js/glow-colors.js` + (missing.length ? `, ${missing.length} pictures not found: ${missing.slice(0, 5).join(", ")}…` : ""));
})();
